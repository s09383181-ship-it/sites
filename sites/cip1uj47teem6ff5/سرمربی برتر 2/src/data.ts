export function mulberry32(seed: number) {
  return function () {
    seed |= 0; seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function generatePlayers(): PTemplate[] {
  const rng = mulberry32(1404);
  const list: PTemplate[] = REAL.map((r, i) => ({ id: i, name: r[0], pos: r[1], rating: r[2], nation: r[3], club: r[4] }));
  const used = new Set(list.map(p => p.name));
  let id = list.length;
  let n = 0;
  while (list.length < 335) {
    const persian = rng() < 0.45;
    const name = persian
      ? `${FA_FIRST[(rng() * FA_FIRST.length) | 0]} ${FA_LAST[(rng() * FA_LAST.length) | 0]}`
      : `${EN_FIRST[(rng() * EN_FIRST.length) | 0]} ${EN_LAST[(rng() * EN_LAST.length) | 0]}`;
    if (used.has(name)) { n++; if (n > 4000) break; continue; }
    used.add(name);
    const pos = POS_SEQ[(rng() * POS_SEQ.length) | 0];
    // توزیع: بیشتر بازیکن‌ها متوسط
    const roll = rng();
    const rating = roll < 0.35 ? 55 + ((rng() * 5) | 0)
      : roll < 0.65 ? 60 + ((rng() * 5) | 0)
      : roll < 0.85 ? 65 + ((rng() * 5) | 0)
      : roll < 0.96 ? 70 + ((rng() * 7) | 0)
      : 77 + ((rng() * 6) | 0);
    list.push({
      id: id++, name, pos, rating,
      nation: persian ? "🇮🇷" : EN_NATION[(rng() * EN_NATION.length) | 0],
      club: CLUBS_POOL[(rng() * CLUBS_POOL.length) | 0],
    });
  }
  return list;
}
export const ALL_PLAYERS: PTemplate[] = generatePlayers();

